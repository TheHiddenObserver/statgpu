"""Experimental device-resident, fixed-index CuPy KDE bootstrap.

Developer experiment only; no public estimator dispatch is changed. Supported
contract: univariate Gaussian, float64, fixed scalar bandwidth factor. Random
indices are supplied explicitly, not generated by this module. CPU orchestration
and scalar validity checks are allowed; numerical arrays never leave the device.
"""
from __future__ import annotations

import math
import operator


def _positive_integer(value, name):
    if isinstance(value, bool):
        raise ValueError(f'{name} must be a positive integer')
    try:
        result = operator.index(value)
    except TypeError as exc:
        raise ValueError(f'{name} must be a positive integer') from exc
    if result <= 0:
        raise ValueError(f'{name} must be a positive integer')
    return result


def plan_workspace(n, q, b, budget, query_chunk=None):
    """Conservative managed-buffer estimate, NOT an allocator hard peak cap.

    Resident inputs, CUDA context and implementation-specific library scratch
    are excluded. Four B*q buffers allow retained draws and quantile sorting;
    vector/reduction allowances cover validation, normalized/gathered weights,
    centered samples and outputs. Two query*n buffers cover density evaluation.
    The minimum is checked before allocating numerical outputs or temporaries.
    """
    n, q, b, budget = (_positive_integer(v, k) for v, k in
                        ((n, 'n'), (q, 'q'), (b, 'b'), (budget, 'budget')))
    fixed = 8 * (4 * b * q + 12 * n + 16 * q + 8 * b + 64)
    per_query = 8 * (2 * n + 8)
    maximum = min(q, (budget - fixed) // per_query)
    if maximum < 1:
        raise MemoryError(f'workspace budget {budget} is below minimum {fixed + per_query}; no downscaling')
    chunk = maximum if query_chunk is None else _positive_integer(query_chunk, 'query_chunk')
    chunk = min(chunk, q)
    if chunk > maximum:
        raise MemoryError('requested query_chunk exceeds workspace budget; no downscaling')
    return {'query_chunk': chunk, 'estimated_bytes': fixed + chunk * per_query,
            'budget_bytes': budget, 'retained_draw_bytes': 8 * b * q}


def _density(x, w, q, bandwidth, query_chunk, xp):
    """Device numerical stage; xp=np is used only for CPU algebra tests."""
    denominator = 1.0 - xp.sum(w * w)
    if not bool(xp.isfinite(denominator)) or float(denominator) <= 1e-15:
        raise ValueError('effective degrees of freedom is too small for covariance estimation')
    mean = xp.sum(x * w)
    centered = x - mean
    centered *= centered
    variance = xp.sum(centered * w) / denominator
    if not bool(xp.isfinite(variance)) or float(variance) < 0:
        raise ValueError('variance is outside the finite experimental numerical envelope')
    variance += xp.maximum(variance * 1e-12, 1e-12)
    # Uncentered public refits are reduction-order sensitive when location
    # dwarfs spread. Do not claim cross-backend parity in that regime.
    if bool(xp.abs(mean) * 2.220446049250313e-16 > xp.sqrt(variance) * 1e-8):
        raise ValueError('location-to-scale conditioning is outside the experimental numerical envelope')
    scaled = variance * (bandwidth * bandwidth)
    if not bool(xp.isfinite(scaled)) or float(scaled) <= 0:
        raise ValueError('scaled variance is outside the finite experimental numerical envelope')
    inverse = 1.0 / scaled
    normalizer = 1.0 / (xp.sqrt(scaled) * math.sqrt(2.0 * math.pi))
    if not bool(xp.isfinite(inverse)) or not bool(xp.isfinite(normalizer)) or float(normalizer) <= 0:
        raise ValueError('normalization is outside the finite experimental numerical envelope')
    out = xp.empty(q.size, dtype=xp.float64)
    for start in range(0, q.size, query_chunk):
        stop = min(start + query_chunk, q.size)
        diff = q[start:stop, None] - x[None, :]
        diff *= diff
        if not bool(xp.all(xp.isfinite(diff))):
            raise ValueError('squared distance is outside the finite experimental numerical envelope')
        diff *= -0.5 * inverse
        if not bool(xp.all(xp.isfinite(diff))):
            raise ValueError('kernel exponent is outside the finite experimental numerical envelope')
        xp.exp(diff, out=diff)
        out[start:stop] = (diff @ w) * normalizer
    if not bool(xp.all(xp.isfinite(out))):
        raise ValueError('density is outside the finite experimental numerical envelope')
    return out


def _compute(x, q, indices, w, bandwidth, confidence_level, query_chunk, xp):
    estimate = _density(x, w, q, bandwidth, query_chunk, xp)
    draws = xp.empty((indices.shape[0], q.size), dtype=xp.float64)
    for row in range(indices.shape[0]):
        sampled_x = x[indices[row]]
        sampled_w = w[indices[row]]
        total = xp.sum(sampled_w)
        if not bool(xp.isfinite(total)) or float(total) <= 0:
            raise ValueError('resample has zero or nonfinite total weight')
        sampled_w /= total
        # Public bootstrap normalizes after gathering, then fit_kde normalizes
        # once more at ingress. Keep both steps in this controlled refit path.
        sampled_w /= xp.sum(sampled_w)
        draws[row] = _density(sampled_x, sampled_w, q, bandwidth, query_chunk, xp)
    alpha = (1.0 - confidence_level) / 2.0
    if q.size == 1:
        # CuPy 13.6's linear-quantile kernel uses the first reduced index
        # as a row offset. For (B, 1), its (1, 2) output loses the singleton
        # row dimension and the upper quantile reads beyond the sorted data.
        # A vector has no kept row axis (offset=0); restore the (2, 1) shape
        # afterwards. This also preserves linear interpolation for B > 1.
        bounds = xp.quantile(draws[:, 0], [alpha, 1.0 - alpha])[:, None]
    else:
        bounds = xp.quantile(draws, [alpha, 1.0 - alpha], axis=0)
    return {'estimate': estimate, 'draws': draws, 'lower': bounds[0], 'upper': bounds[1]}


def native_kde_bootstrap(samples, points, indices, *, weights=None, bandwidth=.4,
                         confidence_level=.95, workspace_bytes=64 * 1024**2,
                         query_chunk=None):
    """Compute fixed-index percentile bootstrap on a single CuPy device.

    Only float64 vectors (or n-by-1 samples/points), integer B-by-n indices,
    and a fixed numeric bandwidth factor are accepted. No dtype conversion,
    implicit device transfer, RNG, host fallback, or public default replacement.
    Numerical overflow/underflow outside the finite experimental envelope fails
    explicitly rather than reproducing the public covariance retry policy.
    """
    import numbers
    import cupy as cp

    for value, name in ((bandwidth, 'bandwidth'), (confidence_level, 'confidence_level')):
        if isinstance(value, bool) or not isinstance(value, numbers.Real) or not math.isfinite(value):
            raise ValueError(f'{name} must be a finite real scalar')
    bandwidth, confidence_level = float(bandwidth), float(confidence_level)
    squared = bandwidth * bandwidth
    if bandwidth <= 0 or not math.isfinite(squared) or squared <= 0:
        raise ValueError('bandwidth squared must be finite and positive')
    if not 0 < confidence_level < 1:
        raise ValueError('confidence_level must lie strictly between zero and one')
    arrays = ((samples, 'samples'), (points, 'points'), (indices, 'indices'))
    if weights is not None:
        arrays += ((weights, 'weights'),)
    for array, name in arrays:
        if not isinstance(array, cp.ndarray):
            raise TypeError(f'{name} must be a CuPy array; no implicit host/device conversion')
        if array.device.id != samples.device.id:
            raise ValueError('all arrays must reside on the same CUDA device')
    for array, name in ((samples, 'samples'), (points, 'points')):
        if array.dtype != cp.float64:
            raise TypeError(f'{name} must have dtype float64')
        if array.ndim != 1 and not (array.ndim == 2 and array.shape[1] == 1):
            raise ValueError(f'{name} must be univariate')
    n, q = samples.size, points.size
    if n < 2 or q < 1:
        raise ValueError('require at least two samples and one query')
    if indices.ndim != 2 or indices.shape[1] != n or indices.shape[0] < 1:
        raise ValueError('indices must have shape (B, n) with B >= 1')
    if indices.dtype.kind not in 'iu':
        raise TypeError('indices must have integer dtype')
    if weights is not None and (weights.ndim != 1 or weights.size != n or weights.dtype != cp.float64):
        raise ValueError('weights must be a float64 vector of length n')
    plan = plan_workspace(n, q, indices.shape[0], workspace_bytes, query_chunk)
    with cp.cuda.Device(samples.device.id):
        x, queries = samples.reshape(-1), points.reshape(-1)
        if not bool(cp.all(cp.isfinite(x))) or not bool(cp.all(cp.isfinite(queries))):
            raise ValueError('samples and points must be finite')
        # Reductions avoid allocating a B*n boolean validation mask.
        if int(cp.min(indices)) < 0 or int(cp.max(indices)) >= n:
            raise ValueError('indices out of range')
        if weights is None:
            w = cp.full(n, 1.0 / n, dtype=cp.float64)
        else:
            if not bool(cp.all(cp.isfinite(weights))) or float(cp.min(weights)) < 0:
                raise ValueError('weights must be finite and nonnegative')
            total = cp.sum(weights)
            if not bool(cp.isfinite(total)) or float(total) <= 0:
                raise ValueError('weights must have finite positive sum')
            w = weights / total
        return _compute(x, queries, indices, w, bandwidth, confidence_level,
                        plan['query_chunk'], cp)
